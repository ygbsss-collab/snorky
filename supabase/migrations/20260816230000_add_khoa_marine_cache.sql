create or replace function public.cleanup_marine_forecast_cache()
returns bigint language plpgsql security definer set search_path=public as $$
declare deleted_count bigint := 0; affected bigint;
begin
  with protected as (select distinct on (grid_key) id from khoa_wave_forecast_cache where status='fresh' order by grid_key, issued_at desc, forecast_at desc), d as (delete from khoa_wave_forecast_cache c where c.fetched_at < now()-interval '7 days' and not exists(select 1 from protected p where p.id=c.id) returning 1) select count(*) into affected from d; deleted_count:=deleted_count+affected;
  with protected as (select distinct on (station_code) id from khoa_current_forecast_cache where status='fresh' order by station_code, issued_at desc, forecast_at desc), d as (delete from khoa_current_forecast_cache c where c.fetched_at < now()-interval '7 days' and not exists(select 1 from protected p where p.id=c.id) returning 1) select count(*) into affected from d; deleted_count:=deleted_count+affected;
  with protected as (select distinct on (station_code) id from khoa_tide_forecast_cache where status='fresh' order by station_code, issued_at desc, forecast_at desc), d as (delete from khoa_tide_forecast_cache c where c.fetched_at < now()-interval '7 days' and not exists(select 1 from protected p where p.id=c.id) returning 1) select count(*) into affected from d; deleted_count:=deleted_count+affected;
  with protected as (select distinct on (source,station_code) id from khoa_marine_observation_cache where status='fresh' order by source,station_code,observed_at desc), d as (delete from khoa_marine_observation_cache c where c.fetched_at < now()-interval '30 days' and not exists(select 1 from protected p where p.id=c.id) returning 1) select count(*) into affected from d; deleted_count:=deleted_count+affected;
  with protected as (select distinct on (region_code) id from kma_mid_sea_forecast_cache where status='fresh' order by region_code,issued_at desc,forecast_at desc), d as (delete from kma_mid_sea_forecast_cache c where c.fetched_at < now()-interval '7 days' and not exists(select 1 from protected p where p.id=c.id) returning 1) select count(*) into affected from d; deleted_count:=deleted_count+affected;
  return deleted_count;
end $$;
revoke all on function public.cleanup_marine_forecast_cache() from public, anon, authenticated;
grant execute on function public.cleanup_marine_forecast_cache() to service_role;
notify pgrst, 'reload schema';
