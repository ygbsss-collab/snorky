create table if not exists public.point_marine_source_mapping (
  point_id bigint primary key references public.points(id) on delete cascade,
  kma_grid text,
  khoa_wave_grid text,
  khoa_current_station text,
  khoa_tide_station text,
  warning_area_code text,
  mapping_source text not null default 'unmapped' check (mapping_source in ('automatic','partial','override','unmapped')),
  mapping_notes text,
  updated_at timestamptz not null default now()
);

create table if not exists public.khoa_wave_forecast_cache (
  id bigint generated by default as identity primary key,
  source text not null default 'KHOA_PRDN_WV3', grid_key text not null,
  issued_at timestamptz not null, forecast_at timestamptz not null,
  payload jsonb not null, normalized_data jsonb not null,
  fetched_at timestamptz not null, updated_at timestamptz not null default now(),
  status text not null default 'fresh' check (status in ('fresh','stale','failed')),
  stale boolean not null default false, response_bytes integer not null default 0,
  item_count integer not null default 0,
  unique (source, grid_key, issued_at, forecast_at)
);

