create index if not exists khoa_wave_latest_idx on public.khoa_wave_forecast_cache(grid_key, forecast_at desc) where status='fresh';
create index if not exists khoa_current_latest_idx on public.khoa_current_forecast_cache(station_code, forecast_at desc) where status='fresh';
create index if not exists khoa_tide_latest_idx on public.khoa_tide_forecast_cache(station_code, forecast_at desc) where status='fresh';
create index if not exists khoa_observation_latest_idx on public.khoa_marine_observation_cache(station_code, observed_at desc) where status='fresh';
create index if not exists kma_mid_sea_latest_idx on public.kma_mid_sea_forecast_cache(region_code, forecast_at desc) where status='fresh';

do $$
declare table_name text;
begin
  foreach table_name in array array['point_marine_source_mapping','khoa_wave_forecast_cache','khoa_current_forecast_cache','khoa_tide_forecast_cache','khoa_marine_observation_cache','kma_mid_sea_forecast_cache'] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on public.%I from anon, authenticated', table_name);
    execute format('grant select, insert, update, delete on public.%I to service_role', table_name);
  end loop;
end $$;

