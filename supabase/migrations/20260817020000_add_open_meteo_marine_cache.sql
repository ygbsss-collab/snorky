create table if not exists public.open_meteo_marine_cache (
  id bigint generated by default as identity primary key,
  cache_key text not null,
  latitude double precision not null,
  longitude double precision not null,
  issued_at timestamptz not null,
  forecast_at timestamptz not null,
  normalized_data jsonb not null,
  source_payload_meta jsonb not null default '{}'::jsonb,
  fetched_at timestamptz not null,
  status text not null default 'fresh' check (status in ('fresh','stale','failed')),
  stale boolean not null default false,
  response_bytes integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (cache_key, issued_at, forecast_at)
);

create index if not exists open_meteo_marine_latest_idx
  on public.open_meteo_marine_cache (cache_key, issued_at desc, forecast_at);
create index if not exists open_meteo_marine_fresh_idx
  on public.open_meteo_marine_cache (cache_key, fetched_at desc)
  where status = 'fresh' and stale = false;

alter table public.open_meteo_marine_cache enable row level security;
revoke all on public.open_meteo_marine_cache from anon, authenticated;
grant select, insert, update, delete on public.open_meteo_marine_cache to service_role;
grant usage, select on sequence public.open_meteo_marine_cache_id_seq to service_role;

create table if not exists public.open_meteo_api_usage (
  id bigint generated by default as identity primary key,
  provider text not null,
  usage_date date not null default current_date,
