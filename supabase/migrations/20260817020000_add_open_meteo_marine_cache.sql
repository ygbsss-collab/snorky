create or replace function public.cleanup_open_meteo_marine_cache()
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare deleted_count bigint;
begin
  -- Keep every forecast row belonging to the latest successful issue per key.
  with latest_issue as (
    select cache_key, max(issued_at) as issued_at
    from open_meteo_marine_cache
    where status = 'fresh'
    group by cache_key
  ), deleted as (
    delete from open_meteo_marine_cache c
    where c.fetched_at < now() - interval '7 days'
      and not exists (
        select 1 from latest_issue l
        where l.cache_key = c.cache_key and l.issued_at = c.issued_at
      )
    returning 1
  )
  select count(*) into deleted_count from deleted;
  return deleted_count;
end $$;

revoke all on function public.cleanup_open_meteo_marine_cache() from public, anon, authenticated;
grant execute on function public.cleanup_open_meteo_marine_cache() to service_role;
notify pgrst, 'reload schema';
