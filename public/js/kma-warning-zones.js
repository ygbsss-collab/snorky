  function pointInPolygon(lat, lng, vs) {
    let inside = false;
    for (let i = 0, j = vs.length - 1; i < vs.length; j = i++) {
      const xi = vs[i][0], yi = vs[i][1];
      const xj = vs[j][0], yj = vs[j][1];
      const intersect = ((yi > lng) !== (yj > lng))
          && (lat < (xj - xi) * (lng - yi) / (yj - yi) + xi);
      if (intersect) inside = !inside;
    }
    return inside;
  }

  function resolveWarningAreaCode(lat, lng) {
    if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;
    for (const zone of ZONES) {
      if (pointInPolygon(lat, lng, zone.polygon)) {
        return zone.code;
      }
    }
    return null;
  }

  function getZoneByCode(code) {
    return ZONES.find(z => z.code === code) || null;
  }

  if (typeof window !== "undefined") {
    window.SNORKYWarningZones = {
      ZONES,
      resolveWarningAreaCode,
      getZoneByCode,
      pointInPolygon
    };
  }
